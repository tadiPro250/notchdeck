import AppKit
import CryptoKit
import Security

/// Recent clipboard items. Items that password managers mark as concealed or transient (the
/// nspasteboard.org convention) are never recorded. With "Remember across restarts" on, text
/// and file items are saved encrypted (AES-GCM, key in the login Keychain); images stay in memory.
final class ClipboardHistory: ObservableObject {
    struct Item: Identifiable, Equatable {
        enum Content: Equatable {
            case text(String)
            case image(NSImage)
            case file(URL)
        }

        var id = UUID()
        let content: Content
        let date: Date
        var pinned = false
    }

    @Published private(set) var items: [Item] = []
    @Published private(set) var lastCopiedID: UUID?

    private let settings: AppSettings
    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var ownChangeCount = -1
    private var timer: Timer?
    private let store = AppSupport.folder.appendingPathComponent("clipboard.sealed")
    private let persists: Bool

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(settings: AppSettings, live: Bool = true) {
        self.settings = settings
        persists = live
        changeCount = pasteboard.changeCount
        guard live else { return }
        if settings.clipboardPersist { load() }
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
    }

    /// Pinned first, then newest.
    var sortedItems: [Item] { items.filter(\.pinned) + items.filter { !$0.pinned } }

    func copy(_ item: Item) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let text): pasteboard.setString(text, forType: .string)
        case .image(let image): pasteboard.writeObjects([image])
        case .file(let url): pasteboard.writeObjects([url as NSURL])
        }
        ownChangeCount = pasteboard.changeCount
        changeCount = ownChangeCount
        if let index = items.firstIndex(where: { $0.id == item.id }), !items[index].pinned {
            let moved = items.remove(at: index)
            items.insert(moved, at: 0)
        }
        lastCopiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
        save()
    }

    func togglePin(_ item: Item) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        save()
    }

    /// Clears everything except pinned items.
    func clear() {
        items.removeAll { !$0.pinned }
        save()
    }

    func showPreview(_ contents: [Item.Content], pinnedFirst: Bool = false) {
        items = contents.enumerated().map { Item(content: $1, date: Date(), pinned: pinnedFirst && $0 == 0) }
    }

    func settingsChanged() {
        if settings.clipboardPersist { save() } else { try? FileManager.default.removeItem(at: store) }
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard settings.clipboardEnabled, changeCount != ownChangeCount else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let content: Item.Content
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let url = urls.first {
            content = .file(url)
        } else if let text = pasteboard.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(text)
        } else if let image = NSImage(pasteboard: pasteboard) {
            content = .image(image)
        } else {
            return
        }

        if let existing = items.firstIndex(where: { $0.content == content }) {
            if items[existing].pinned { return }
            items.remove(at: existing)
        }
        items.insert(Item(content: content, date: Date()), at: 0)
        let unpinned = items.filter { !$0.pinned }
        if unpinned.count > settings.clipboardLimit, let oldest = unpinned.last {
            items.removeAll { $0.id == oldest.id }
        }
        save()
    }

    // MARK: Encrypted persistence

    private struct Saved: Codable {
        var text: String?
        var file: String?
        var date: Date
        var pinned: Bool
    }

    /// Keychain reads can block for seconds (a pending Keychain prompt, iCloud Keychain syncing),
    /// so the key is fetched on this queue and never on the main thread.
    private static let keyQueue = DispatchQueue(label: "notchdeck.clipboard.key")
    private static var cachedKey: SymmetricKey?

    private func save() {
        guard persists, settings.clipboardPersist else { return }
        let saved: [Saved] = items.compactMap { item in
            switch item.content {
            case .text(let text): Saved(text: text, file: nil, date: item.date, pinned: item.pinned)
            case .file(let url): Saved(text: nil, file: url.path, date: item.date, pinned: item.pinned)
            case .image: nil
            }
        }
        guard let plain = try? JSONEncoder().encode(saved) else { return }
        let store = store
        Self.keyQueue.async {
            guard let key = Self.cachedKey ?? Self.key(),
                  let sealed = try? AES.GCM.seal(plain, using: key).combined else { return }
            Self.cachedKey = key
            try? sealed.write(to: store, options: .atomic)
        }
    }

    private func load() {
        let store = store
        Self.keyQueue.async { [weak self] in
            guard let key = Self.cachedKey ?? Self.key() else { return }
            Self.cachedKey = key
            guard let data = try? Data(contentsOf: store),
                  let box = try? AES.GCM.SealedBox(combined: data),
                  let plain = try? AES.GCM.open(box, using: key),
                  let saved = try? JSONDecoder().decode([Saved].self, from: plain) else { return }
            DispatchQueue.main.async {
                guard let self else { return }
                let loaded: [Item] = saved.compactMap { entry in
                    if let text = entry.text { return Item(content: .text(text), date: entry.date, pinned: entry.pinned) }
                    if let path = entry.file { return Item(content: .file(URL(fileURLWithPath: path)), date: entry.date, pinned: entry.pinned) }
                    return nil
                }
                // Anything copied while the key was loading stays on top.
                self.items = self.items + loaded.filter { old in !self.items.contains { $0.content == old.content } }
            }
        }
    }

    /// A 256-bit key kept in the login Keychain, created on first use.
    private static func key() -> SymmetricKey? {
        let query: [String: Any] = [kSecClass as String: kSecClassGenericPassword,
                                    kSecAttrService as String: "NotchDeck clipboard",
                                    kSecAttrAccount as String: "history-key",
                                    kSecReturnData as String: true]
        var result: CFTypeRef?
        if SecItemCopyMatching(query as CFDictionary, &result) == errSecSuccess, let data = result as? Data {
            return SymmetricKey(data: data)
        }
        let key = SymmetricKey(size: .bits256)
        let data = key.withUnsafeBytes { Data($0) }
        let add: [String: Any] = [kSecClass as String: kSecClassGenericPassword,
                                  kSecAttrService as String: "NotchDeck clipboard",
                                  kSecAttrAccount as String: "history-key",
                                  kSecAttrAccessible as String: kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly,
                                  kSecValueData as String: data]
        return SecItemAdd(add as CFDictionary, nil) == errSecSuccess ? key : nil
    }
}
